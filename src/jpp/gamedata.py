def _pairs(blob):
    return (e.split("=", 1) for e in blob.replace("\n", "").split(",") if e)


SPECIES = {int(k): v for k, v in _pairs(_SPECIES)}
TYPES = {int(k): v for k, v in _pairs(_TYPES)}
# move id: (name, type, base power, max PP)
MOVES = {
    int(k): (lambda n, t, p, pp: (n.replace("_", " "), t, int(p), int(pp)))(
        *v.split(":")
    )
    for k, v in _pairs(_MOVES)
}
# (attacking type, defending type): multiplier; unlisted pairs are 1.0
TYPE_CHART = {tuple(k.split(">")): float(v) for k, v in _pairs(_CHART)}


def species_name(i):
    return SPECIES.get(i, f"MON_{i:02X}")


def type_name(i):
    return TYPES.get(i, f"TYPE_{i:02X}")


def move(i):
    return MOVES.get(i, (f"MOVE_{i:02X}", "NORMAL", 0, 0))
